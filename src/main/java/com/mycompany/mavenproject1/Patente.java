public class Patente {
  private int ientificador;
  private String nome;
  private String descricao;
  private int nivelhierarquico;

    public int getIentificador() {
        return ientificador;
    }

    public void setIentificador(int ientificador) {
        this.ientificador = ientificador;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public int getNivelhierarquico() {
        return nivelhierarquico;
    }

    public void setNivelhierarquico(int nivelhierarquico) {
        this.nivelhierarquico = nivelhierarquico;
    }
}
