public class Ocorrencia {
     private int ientificadorOcorrencia;
     private String nome;
     private String hora;
     private String Status;
     private String tipo;

    public int getIentificadorOcorrencia() {
        return ientificadorOcorrencia;
    }

    public void setIentificadorOcorrencia(int ientificadorOcorrencia) {
        this.ientificadorOcorrencia = ientificadorOcorrencia;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getHora() {
        return hora;
    }

    public void setHora(String hora) {
        this.hora = hora;
    }

    public String getStatus() {
        return Status;
    }

    public void setStatus(String Status) {
        this.Status = Status;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }
}
