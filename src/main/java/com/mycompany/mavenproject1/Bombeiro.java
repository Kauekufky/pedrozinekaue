public class Bombeiro {
    private int identificadorBombeiro;
    private String nome;
    private int cpf;
    private String matricula;
    private int datadeNascimento;
    private int patente;
    private int especialidade;
    private int contato;
    private int status;
    public int getIdentificadorBombeiro() {
        return identificadorBombeiro;
    }

    public void setIdentificadorBombeiro(int identificadorBombeiro) {
        this.identificadorBombeiro = identificadorBombeiro;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public int getCpf() {
        return cpf;
    }

    public void setCpf(int cpf) {
        this.cpf = cpf;
    }

    public String getMatricula() {
        return matricula;
    }

    public void setMatricula(String matricula) {
        this.matricula = matricula;
    }

    public int getDatadeNascimento() {
        return datadeNascimento;
    }

    public void setDatadeNascimento(int datadeNascimento) {
        this.datadeNascimento = datadeNascimento;
    }

    public int getPatente() {
        return patente;
    }

    public void setPatente(int patente) {
        this.patente = patente;
    }

    public int getEspecialidade() {
        return especialidade;
    }

    public void setEspecialidade(int especialidade) {
        this.especialidade = especialidade;
    }

    public int getContato() {
        return contato;
    }

    public void setContato(int contato) {
        this.contato = contato;
    }

    public int getStatus() {
        return status;
    }

    public void setStatus(int status) {
        this.status = status;
    }
    
}
